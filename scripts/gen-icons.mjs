#!/usr/bin/env node
/**
 * Writes lib/constants/icons.ts: the SVG bodies of every Lucide icon the app
 * names. AppIcon renders from that map, so icons cost a few bytes each and no
 * icon runtime ships to the browser.
 *
 * Run after using a new icon:  node scripts/gen-icons.mjs
 * It scans pages/, components/, layouts/, app.vue and error.vue for
 * "lucide:<name>" strings, so always write icon names out in full.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs"
import { join } from "node:path"
import { createRequire } from "node:module"

const require = createRequire(import.meta.url)
const lucide = require("@iconify-json/lucide/icons.json")
const roots = ["pages", "components", "layouts", "app.vue", "error.vue"]

function files(path) {
  if (statSync(path).isFile()) return [path]
  return readdirSync(path).flatMap((name) => files(join(path, name)))
}

const names = new Set()
for (const file of roots.flatMap(files)) {
  if (!/\.(vue|ts)$/.test(file)) continue
  for (const match of readFileSync(file, "utf8").matchAll(/lucide:([a-z0-9-]+)/g)) names.add(match[1])
}

const out = {}
for (const name of [...names].sort()) {
  const target = lucide.icons[name] ?? lucide.icons[lucide.aliases?.[name]?.parent]
  if (!target) throw new Error(`Unknown Lucide icon: ${name}`)
  out[name] = target.body
}

writeFileSync(
  "lib/constants/icons.ts",
  "// Generated by scripts/gen-icons.mjs from @iconify-json/lucide. Do not edit by hand.\n"
  + "// Lucide icons are 24×24; each value is the inner SVG markup.\n"
  + `export const ICONS: Record<string, string> = ${JSON.stringify(out, null, 2)}\n`,
)
console.log(`lib/constants/icons.ts: ${Object.keys(out).length} icons`)
